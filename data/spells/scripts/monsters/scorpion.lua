local combat = Combat()
combat:setParameter(COMBAT_PARAM_BLOCKARMOR, true)
combat:setParameter(COMBAT_PARAM_BLOCKSHIELD, true)
combat:setParameter(COMBAT_PARAM_TYPE, COMBAT_PHYSICALDAMAGE)

local condition = Condition(CONDITION_POISON)
condition:setParameter(CONDITION_PARAM_DELAYED, true)
condition:addDamage(1, 3000, -20)
condition:addDamage(2, 3000, -19)
condition:addDamage(3, 3000, -17)
condition:addDamage(4, 3000, -14)
condition:addDamage(5, 3000, -10)
condition:addDamage(4, 3000, -5)
condition:addDamage(3, 3000, -4)
condition:addDamage(5, 3000, -3)
condition:addDamage(4, 3000, -2)
condition:addDamage(10, 3000, -1)
combat:addCondition(condition)

function onCastSpell(cid, var)
    combat:execute(cid, var)
end
